-- Run only in a fresh test database; this script rolls back all objects/data.
BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role NOLOGIN BYPASSRLS;
  END IF;
END
$$;
ALTER ROLE service_role BYPASSRLS;

CREATE SCHEMA auth;
CREATE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
GRANT USAGE ON SCHEMA auth TO anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;

CREATE TABLE public.profiles (
  id uuid PRIMARY KEY,
  nickname text,
  role text NOT NULL DEFAULT 'visitor'
);
CREATE TABLE public.competition_attendance (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.profiles(id),
  status text NOT NULL,
  points_awarded integer NOT NULL DEFAULT 0,
  completion_points_awarded integer NOT NULL DEFAULT 0
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.competition_attendance ENABLE ROW LEVEL SECURITY;

CREATE POLICY profile_self_read
ON public.profiles FOR SELECT TO authenticated
USING (id = auth.uid());

CREATE POLICY attendance_member_select
ON public.competition_attendance FOR SELECT TO authenticated
USING (user_id = auth.uid());

GRANT SELECT ON public.profiles, public.competition_attendance
TO authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public
TO authenticated, service_role;

