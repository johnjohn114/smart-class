CREATE VIEW public.activity_member_stats
WITH (security_invoker = true)
AS
SELECT
  a.user_id,
  COALESCE(NULLIF(BTRIM(p.nickname), ''), '會員') AS nickname,
  COUNT(*) FILTER (WHERE a.status = ANY (ARRAY['checked_in'::text, 'late'::text]))::integer AS attended_count,
  COUNT(*) FILTER (WHERE a.status = 'late'::text)::integer AS late_count,
  COUNT(*) FILTER (WHERE a.status = 'no_show'::text)::integer AS no_show_count,
  COALESCE(SUM(a.points_awarded), 0::bigint)::integer AS checkin_points,
  COALESCE(SUM(a.completion_points_awarded), 0::bigint)::integer AS completion_points,
  (COALESCE(SUM(a.points_awarded), 0::bigint) + COALESCE(SUM(a.completion_points_awarded), 0::bigint))::integer AS activity_points
FROM public.competition_attendance AS a
LEFT JOIN public.profiles AS p ON p.id = a.user_id
GROUP BY a.user_id;

REVOKE ALL PRIVILEGES ON TABLE public.activity_member_stats FROM PUBLIC, anon, authenticated, service_role;
GRANT SELECT ON TABLE public.activity_member_stats TO authenticated, service_role;

-- Anonymous access must be denied at the view ACL layer.
SET ROLE anon;
DO $$
BEGIN
  BEGIN
    PERFORM count(*) FROM public.activity_member_stats;
    RAISE EXCEPTION 'anon unexpectedly read activity_member_stats';
  EXCEPTION
    WHEN insufficient_privilege THEN NULL;
  END;
END
$$;
RESET ROLE;

-- A signed-in member sees only their own row through the invoker view + RLS.
SELECT set_config('request.jwt.claim.sub', '11111111-1111-4111-8111-111111111111', false);
SET ROLE authenticated;
DO $$
DECLARE row_count integer; own_count integer;
BEGIN
  SELECT count(*) INTO row_count FROM public.activity_member_stats;
  SELECT attended_count INTO own_count
  FROM public.activity_member_stats
  WHERE user_id = auth.uid();
  IF row_count <> 1 OR own_count <> 2 THEN
    RAISE EXCEPTION 'authenticated member did not see only their own stats';
  END IF;
END
$$;
RESET ROLE;

-- The trusted service role can read all rows for the server-side public projection.
SET ROLE service_role;
DO $$
DECLARE row_count integer;
BEGIN
  SELECT count(*) INTO row_count FROM public.activity_member_stats;
  IF row_count <> 2 THEN
    RAISE EXCEPTION 'service_role should read both rows for leaderboard aggregation';
  END IF;
END
$$;
RESET ROLE;

DO $$
DECLARE invoker_enabled boolean;
BEGIN
  SELECT COALESCE('security_invoker=true' = ANY(reloptions), false)
  INTO invoker_enabled
  FROM pg_class
  WHERE oid = 'public.activity_member_stats'::regclass;
  IF NOT invoker_enabled THEN
    RAISE EXCEPTION 'activity_member_stats must be security_invoker';
  END IF;
END
$$;

ROLLBACK;
